    /** Returns a pointer to the q_col table for the given line index, or nullptr. */
    static const double (*getQcolTable(int lineIdx))[qcNumT]
    {
        switch (lineIdx)
        {
            case LineIndex::NII6548: return log_qcol_NII_6548;
            case LineIndex::NII6583: return log_qcol_NII_6583;
            case LineIndex::OI6300: return logQcolOI6300;
            case LineIndex::OI6364: return logQcolOI6364;
            case LineIndex::OII3729: return log_qcol_OII_3729;
            case LineIndex::OII3726: return log_qcol_OII_3726;
            case LineIndex::OIII4363: return log_qcol_OIII_4363;
            case LineIndex::OIII4959: return log_qcol_OIII_4959;
            case LineIndex::OIII5007: return log_qcol_OIII_5007;
            case LineIndex::SII6716: return log_qcol_SII_6716;
            case LineIndex::SII6731: return log_qcol_SII_6731;
            default: return nullptr;
        }
    }

    /** Internal: 2D Lagrange interpolation of log q_col table */
    static double interpolateQcolTable(const double table[qcNumNe][qcNumT], double T, double ne)
    {
        // Clamp to grid
        double logT = (T < 1e2) ? qcMinLogT : ((T > 1e7) ? qcMaxLogT : std::log10(T));
        double logN = (ne < 1e1) ? qcMinLogN : ((ne > 1e10) ? qcMaxLogN : std::log10(ne));

        // Temperature index
        int iT = static_cast<int>(std::floor(qcInvDexT * (logT - qcMinLogT)));
        if (iT > qcNumT - qcOrderPlusOne) iT = qcNumT - qcOrderPlusOne;
        if (iT < 0) iT = 0;

        // Density index
        int iN = static_cast<int>(std::floor(qcInvDexN * (logN - qcMinLogN)));
        if (iN > qcNumNe - qcOrderPlusOne) iN = qcNumNe - qcOrderPlusOne;
        if (iN < 0) iN = 0;

        // Build local grid points for interpolation
        double xT[4], xN[4], buffer[4];
        for (int i = 0; i < 4; ++i)
        {
            xT[i] = qc_logT(iT + i);
            xN[i] = qc_logne(iN + i);
        }

        // Interpolate in T for each of 4 density points
        for (int i = 0; i < 4; ++i)
        {
            double yT[4];
            for (int j = 0; j < 4; ++j) yT[j] = table[iN + i][iT + j];
            buffer[i] = lagrange4(xT, yT, logT);
        }

        // Interpolate in ne
        return std::pow(10., lagrange4(xN, buffer, logN));
    }

    double metalLineQcol(int lineIdx, double T, double ne)
    {
        auto table = getQcolTable(lineIdx);
        if (!table) return 0.;
        return interpolateQcolTable(table, T, ne);
    }

