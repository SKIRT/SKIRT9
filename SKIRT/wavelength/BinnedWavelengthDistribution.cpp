#include "BinnedWavelengthDistribution.hpp"
#include "Random.hpp"

//////////////////////////////////////////////////////////////////////

double BinnedWavelengthDistribution::wavelengthInBin(int ell) const
{
    auto wlg = wavelengthGrid();
    return wlg->leftBorder(ell) + random()->uniform() * wlg->effectiveWidth(ell);
}

